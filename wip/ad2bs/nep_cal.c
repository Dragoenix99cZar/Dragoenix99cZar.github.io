// Helper struct to hold AD date components
typedef struct {
    int year;
    int month;
    int day;
} ADDate;

// Helper to count total days from BS anchor
int count_total_days_bs(int year, int month, int day) {
    int total_days = 0;
    int year_idx = year - ANCHOR_BS_YEAR;
    for (int y = 0; y < year_idx; y++) {
        for (int m = 0; m < 12; m++) {
            total_days += BS_DATA[y][m];
        }
    }
    for (int m = 0; m < month - 1; m++) {
        total_days += BS_DATA[year_idx][m];
    }
    total_days += (day - 1);
    return total_days;
}

// Helper: check AD leap year
int is_ad_leap(int year) {
    return (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0);
}

// Exported: BS to AD packed integer (returns YYYYMMDD, e.g., 20260926)
// Anchor: 1970-01-01 BS corresponds to 1913-04-13 AD
__attribute__((visibility("default")))
int btoa(int bs_year, int bs_month, int bs_day) {
    int total_days = count_total_days_bs(bs_year, bs_month, bs_day);
    
    // 1913-04-13 epoch base day addition
    int ad_year = 1913;
    int ad_month = 4;
    int ad_day = 13;
    
    // Add total_days to the anchor date using standard C Gregorian math
    ad_day += total_days;
    
    int m_days[] = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
    
    while (1) {
        int leap = is_ad_leap(ad_year);
        int days_in_cur_month = m_days[ad_month];
        if (ad_month == 2 && leap) days_in_cur_month = 29;
        
        if (ad_day <= days_in_cur_month) break;
        
        ad_day -= days_in_cur_month;
        ad_month++;
        if (ad_month > 12) {
            ad_month = 1;
            ad_year++;
        }
    }
    
    return (ad_year * 10000) + (ad_month * 100) + ad_day;
}

// Exported: AD to BS packed integer (returns YYYYMMDD, e.g., 20830610)
__attribute__((visibility("default")))
int atob(int year, int month, int day) {
    int m_days[] = {0, 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
    int target_days = day;
    
    for (int yr = 1913; yr < year; yr++) {
        target_days += is_ad_leap(yr) ? 366 : 365;
    }
    for (int mo = 1; mo < month; mo++) {
        int days = m_days[mo];
        if (mo == 2 && is_ad_leap(year)) days = 29;
        target_days += days;
    }
    
    int total_days = target_days - 103; // Anchor offset for 1913-04-13
    
    int bs_year = ANCHOR_BS_YEAR;
    int y_idx = 0;
    
    while (1) {
        int year_total_days = 0;
        for (int m = 0; m < 12; m++) {
            year_total_days += BS_DATA[y_idx][m];
        }
        if (total_days < year_total_days) break;
        total_days -= year_total_days;
        y_idx++;
        bs_year++;
    }
    
    int bs_month = 1;
    int m_idx = 0;
    while (1) {
        int m_days_val = BS_DATA[y_idx][m_idx];
        if (total_days < m_days_val) break;
        total_days -= m_days_val;
        m_idx++;
        bs_month++;
    }
    
    int bs_day = total_days + 1;
    return (bs_year * 10000) + (bs_month * 100) + bs_day;
}

